export const KEPT_CARDS=[];

export function cardUnlocked(id,level) {
    return unlockLevel(id)<=level;
}

export function unlockLevel(id) {
    for (const lv in UNLOCKS) {
        if (UNLOCKS[lv].includes(id)) {
            return Number(lv);
        }
    }
    return 1;
}

export function unlockedCards(level) {
    const out=[];
    for (const lv in UNLOCKS) {
        if (Number(lv)<=level) {
            out.push(...UNLOCKS[lv]);
        }
    }
    return out.filter(id=>CARDS[id]);
}

export function isUlt(id) {
    return CARDS[id].rarity==='rare';
}

